-- ★ 编号说明：TASKS-V2 写的是 V8__group.sql，但 V8 已被「信用账本」、V9 已被「申诉」占用，
--   已落库的脚本不能回改（破 Flyway checksum），故顺延 V10。
--
-- ★ 不新建占用表（DESIGN §7.2）：锁定后按桌位座位逐条写 t_reservation + t_reservation_slot，
--   并发防重继续由 uk_slot_seat_date_idx 兜底。组队若另立一张占用表，平面图、统计、
--   暂离、候补释放挂钩全都要认两张表 —— 那是 V1 反复修过的「两处真相」事故。
--   t_reservation 只多一个 group_id 作为「这些预约属于同一次下单」的关联键，不参与占用判定。
--
-- ★ t_zone_grant（考研专座这类名单资格）本次不建：DESIGN §7.1 把它和组队画在同一个脚本里，
--   但 V2 目前没有任何任务消费它，资格判定的真实来源仍是 t_zone.eligible_roles。
--   空转的表 + 无读它的判定链只会让人误以为名单已经生效；等名单场景落地时再起一条迁移。
--
-- ★ 邀请码唯一索引带 NULL：FORMING 之外的队伍没有码，H2/MySQL 的唯一索引都不把
--   「多行 NULL」视为冲突，所以未生成码的队伍可以并存（与 t_leave_record 的 open_flag 同理）。
-- =====================================================================

CREATE TABLE IF NOT EXISTS t_group (
    id                BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    leader_id         BIGINT       NOT NULL,
    floor_id          BIGINT       NOT NULL,
    zone_id           BIGINT       NOT NULL,
    table_id          BIGINT       NULL,                        -- 整桌下单必填；NULL 表示按分区散座组
    reserve_date      DATE         NOT NULL,
    start_slot        INT          NOT NULL,                    -- 30 分钟格序号（含）
    end_slot          INT          NOT NULL,                    -- 30 分钟格序号（不含）
    invite_code       VARCHAR(10)  NULL,
    invite_expire_time TIMESTAMP   NULL,
    min_members       INT          NOT NULL,
    max_members       INT          NOT NULL,
    lock_time         TIMESTAMP    NOT NULL,                    -- 开始前 30 分钟，此后禁止增减成员
    status            VARCHAR(20)  NOT NULL,                    -- FORMING/LOCKED/RESERVED/CHECKED_IN/COMPLETED/CANCELLED/FAILED
    create_time       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_group_invite ON t_group (invite_code);
CREATE INDEX IF NOT EXISTS idx_group_leader ON t_group (leader_id, status);
CREATE INDEX IF NOT EXISTS idx_group_status ON t_group (status, lock_time);

CREATE TABLE IF NOT EXISTS t_group_member (
    id            BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id      BIGINT       NOT NULL,
    user_id       BIGINT       NOT NULL,
    member_role   VARCHAR(10)  NOT NULL,                        -- LEADER / MEMBER
    invite_status VARCHAR(20)  NOT NULL,                        -- INVITED/CONFIRMED/DECLINED/EXPIRED
    confirm_time  TIMESTAMP    NULL,
    seat_id       BIGINT       NULL,                            -- 锁定后实际占住的座位；未分配为 NULL
    attend_status VARCHAR(20)  NOT NULL,                        -- UNKNOWN/PRESENT/ABSENT（T-V2-16 用）
    create_time   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_group_user ON t_group_member (group_id, user_id);
CREATE INDEX IF NOT EXISTS idx_group_member_user ON t_group_member (user_id, invite_status);

ALTER TABLE t_reservation ADD COLUMN IF NOT EXISTS group_id BIGINT NULL;
CREATE INDEX IF NOT EXISTS idx_resv_group ON t_reservation (group_id);
