-- =====================================================================
-- V4：分区建模（S1 / T-V2-05）
--   · 空间层级由「楼层 → 座位」扩成「楼层 → 分区 → (桌位) → 座位」；
--     分区是规则载体（时长上限 / 暂离 / 组队 / 可见角色），不给单个座位配规则。
--   · 座位旧 zone（VARCHAR 文本）列保留一个大版本做展示兼容，新代码一律读 zone_id。
--   · 回填分两条路，互不冲突：
--       - 遗留库（V1 升上来）：本脚本给每个既有楼层建一个 DEFAULT 分区并挂接所有座位；
--         此时 t_seat 已有数据，故末尾 UPDATE 是「无孤儿」的真正保障。
--       - 全新库：Flyway 先于 DataInitializer 执行，t_floor 尚为空 → 本脚本不产生任何分区，
--         真实分区由种子创建。
-- =====================================================================

CREATE TABLE IF NOT EXISTS t_zone (
    id                BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    floor_id          BIGINT       NOT NULL,                 -- 所属楼层
    name              VARCHAR(50)  NOT NULL,                 -- 分区名（如「静音自习区」）
    code              VARCHAR(20)  NOT NULL,                 -- 楼层内唯一编码，如 1F-SILENT
    zone_type         VARCHAR(30)  NOT NULL,                 -- SILENT/SEMINAR/E_READING/LOUNGE/EXAM_PREP/TEACHER_ONLY
    status            VARCHAR(20)  NOT NULL DEFAULT 'OPEN',  -- OPEN / CLOSED
    max_duration_min  INT          NOT NULL DEFAULT 240,     -- 单次时长上限（分钟）
    daily_cap_min     INT          NULL,                     -- 单日累计上限；NULL = 不设分区上限
    advance_days      INT          NOT NULL DEFAULT 3,       -- 可提前预约天数（含当天）
    allow_discuss     VARCHAR(10)  NOT NULL DEFAULT 'NO',    -- NO / LOW / YES
    allow_leave       BOOLEAN      NOT NULL DEFAULT TRUE,    -- 是否允许暂离
    leave_max_min     INT          NOT NULL DEFAULT 60,      -- 本区单次暂离封顶
    leave_daily_limit INT          NOT NULL DEFAULT 3,       -- 本区每日暂离次数
    allow_group       BOOLEAN      NOT NULL DEFAULT FALSE,   -- 是否支持组队预约
    group_required    BOOLEAN      NOT NULL DEFAULT FALSE,   -- 研讨协作区：仅接受整组预约
    visible_roles     VARCHAR(100) NOT NULL DEFAULT 'STUDENT,TEACHER,LIBRARIAN,SYS_ADMIN',
    eligible_roles    VARCHAR(100) NOT NULL DEFAULT 'STUDENT,TEACHER,LIBRARIAN,SYS_ADMIN',
    sort_order        INT          NOT NULL DEFAULT 0,
    remark            VARCHAR(200) NULL,
    create_time       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_zone_floor_code ON t_zone (floor_id, code);
CREATE INDEX IF NOT EXISTS idx_zone_floor ON t_zone (floor_id);

ALTER TABLE t_seat ADD COLUMN IF NOT EXISTS zone_id BIGINT NULL;
CREATE INDEX IF NOT EXISTS idx_seat_zone ON t_seat (zone_id);

-- ===== 遗留库回填：每个既有楼层补一个兜底分区，再把未挂接的座位归入 =====
INSERT INTO t_zone (floor_id, name, code, zone_type, status, max_duration_min, advance_days,
                    allow_discuss, allow_leave, leave_max_min, leave_daily_limit,
                    allow_group, group_required, sort_order, remark)
SELECT f.id, '默认分区', 'DEFAULT', 'SILENT', 'OPEN', 240, 7,
       'NO', TRUE, 60, 3, FALSE, FALSE, 0, 'V1 升级自动创建，可在管理面改名或删除'
FROM t_floor f
WHERE NOT EXISTS (SELECT 1 FROM t_zone z WHERE z.floor_id = f.id);

UPDATE t_seat
SET zone_id = (SELECT z.id FROM t_zone z WHERE z.floor_id = t_seat.floor_id AND z.code = 'DEFAULT')
WHERE zone_id IS NULL;
