--
-- ★ 排队键是「分区 + 日期 + 起始时段」，不是某个座位：释放的是「一个位置」而不是「那一把椅子」，
--   把 seat_id 写进队列就会遇到「那把椅子又被别人占了，整条队列卡死」。
--   确认时按当时的空位现挑一座，并重新走完整校验链（信用 / 累计 / 重叠 / 冲突）。
--
-- ★ active_flag 的 NULL 唯一技巧（与 t_leave_record.open_flag、t_reservation 的
--   uk_slot_seat_date_idx 同一套路）：活动中的行 = 1，终态一律置 NULL。
--   H2 与 MySQL 的唯一索引都不把「多行 NULL」视为冲突，所以一个人可以留下任意多条
--   历史候补记录，但同时只能有有限条活动记录 —— 这条约束由索引兜底而不是靠应用层「先查再插」，
--   因为并发下先查再插必然漏（申诉表 uk_appeal_violation 已经验过一次）。
--
-- ★ 超时不记违规：候补是「没抢到位置」而不是「放了鸽子」，
--   把爽约账记到没占到座位的人头上，等于惩罚使用候补功能。
-- =====================================================================

CREATE TABLE IF NOT EXISTS t_waitlist (
    id                BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id           BIGINT       NOT NULL,
    floor_id          BIGINT       NOT NULL,
    zone_id           BIGINT       NOT NULL,
    table_id          BIGINT       NULL,                          -- 组队区的整桌候补用，普通区为 NULL
    reserve_date      DATE         NOT NULL,
    start_slot        INT          NOT NULL,                      -- 排队键的一部分（起始格）
    end_slot          INT          NOT NULL,                      -- 开区间边界，确认时按此下单
    status            VARCHAR(20)  NOT NULL,                      -- WAITING/OFFERED/CONFIRMED/EXPIRED/CANCELLED
    active_flag       SMALLINT     NULL,                          -- 活动中=1，终态=NULL（配合唯一索引）
    offered_time       TIMESTAMP   NULL,
    offer_expire_time  TIMESTAMP   NULL,
    create_time       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time       TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 同一用户对同一（分区,日期,起始时段）只能有一条活动候补位
CREATE UNIQUE INDEX IF NOT EXISTS uk_waitlist_active
    ON t_waitlist (user_id, zone_id, reserve_date, start_slot, active_flag);
CREATE INDEX IF NOT EXISTS idx_waitlist_zone_state
    ON t_waitlist (zone_id, reserve_date, start_slot, status);
CREATE INDEX IF NOT EXISTS idx_waitlist_user
    ON t_waitlist (user_id, active_flag);

