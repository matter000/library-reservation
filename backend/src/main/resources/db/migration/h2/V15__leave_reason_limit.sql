-- V15：暂离计次口径修正（T-V2-24 收口发现的实现与 PRD 冲突）
--
-- ★ 为什么要有这一版：
--   PRD §6.2 的核心约束 1 说「每日暂离**总**次数 ≤ 3 次（考研专座放宽至 5 次）」——
--   总数挂在**分区**上；同一节的表里又写「就餐 每日最多 2 次」「接听/短休 每日最多 3 次」——
--   这是**按原因**各自的次数。V7 把两者塞进了同一个 min()：
--       当日总数 < min(zone.leave_daily_limit, reason.daily_limit)
--   而六个原因的 daily_limit 都种成 3，于是考研专座的 5 永远被 3 夹住（PRD §12-13 未达成），
--   并且「就餐每天 2 次」这条从来没有生效过（原因上限被拿去当总数上限用了）。
--   更要命的是「我的预约」按钮可用性只看分区值，提交却看 min()：
--   考研专座第 4 次暂离时按钮亮着、提交报 4096 —— 正是代码注释里自己禁止的口径分裂。
--
-- ★ 本版只改数据，把原因的次数改成 PRD 写的值；判定逻辑同步在 LeaveService 里拆开：
--   总数看分区（zone.leave_daily_limit），单原因次数看原因表（reason.daily_limit）。
--   这样 5 次这一档真的可达，就餐 2 次也第一次真正生效。
--
-- ★ 不改 V7：已落库脚本一改就破 Flyway checksum，演示库直接起不来。
-- =====================================================================

UPDATE t_leave_reason SET daily_limit = 2 WHERE code = 'MEAL';
