CREATE TABLE IF NOT EXISTS t_appeal (
    id           BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    violation_id BIGINT       NOT NULL,
    user_id      BIGINT       NOT NULL,                        -- 冗余存一份：学生面「我的申诉」不必回头 join 违规
    reason       VARCHAR(500) NOT NULL,                        -- 学生事由，必填
    status       VARCHAR(20)  NOT NULL,                        -- PENDING / APPROVED / REJECTED / ESCALATED / FINAL_JUDGED
    handler_id   BIGINT       NULL,                            -- 裁定人（终审同样记，审计里能看到是谁结的案）
    handler_role VARCHAR(20)  NULL,                            -- LIBRARIAN / SYS_ADMIN —— 用来区分「复核」与「终审」
    reply        VARCHAR(500) NULL,                            -- 裁定说明；驳回时必填（学生要看得懂为什么不算）
    create_time  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    handle_time  TIMESTAMP    NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_appeal_violation ON t_appeal (violation_id);
CREATE INDEX IF NOT EXISTS idx_appeal_status ON t_appeal (status, id);
