--   V12「候补」、V13「通知」占用，已落库脚本不能回改（破 Flyway checksum），故顺延 V14。
--
-- ★ 产品红线（PRD §12-25）：**机器只登记疑点，绝不自动释放座位**。
--   生成器（PatrolTaskGenerator，10 分钟一轮）只做「算 + 写一条 PENDING 任务」，
--   释放必须来自馆员的一次人工处置（RELEASE 复用强制释放，必填原因 + 通知 + 审计）。
--   所以本表没有任何「自动处理」列，也没有定时任务会改 status。
--
-- ★ open_flag 的 NULL 唯一技巧（与 t_leave_record.open_flag、t_waitlist.active_flag 同一套路）：
--   PENDING 的行 = 1，处置完置 NULL。于是 uk_patrol_open(seat_id, open_flag) 天然表达
--   「同一座位同时只能挂一个未处理疑点」，10 分钟一轮的重复扫描因此是幂等的，
--   而历史任务（已处置）可以无限多条 —— 馆员要能回溯「这张椅子上周被提醒过三次」。
--   H2 与 MySQL 都不把多行 NULL 视为唯一冲突，这正是该技巧的前提。
--
-- ★ evidence 用 CLOB 存 JSON，且与 t_violation 一样「无证据不落账」：
--   生成时就把判定输入（连续时长、应归时刻、签到时刻、阈值）写进去，
--   馆员处置页直接渲染这份可读证据，而不是让馆员去猜系统为什么报警。
-- =====================================================================

CREATE TABLE IF NOT EXISTS t_patrol_task (
    id               BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    floor_id         BIGINT       NOT NULL,
    zone_id          BIGINT       NOT NULL,
    seat_id          BIGINT       NOT NULL,
    reservation_id   BIGINT       NULL,                          -- 无预约占用（人工登记）时为 NULL
    type             VARCHAR(30)  NOT NULL,                      -- SUSPECTED_OCCUPY/GROUP_NO_ATTEND/OVERDUE_HOLDING/MANUAL
    level            VARCHAR(10)  NOT NULL,                      -- HIGH/MID/LOW
    reason           VARCHAR(200) NOT NULL,                      -- 生成依据的可读文案（含关键时刻）
    evidence         CLOB         NOT NULL,                      -- 判定输入 JSON，无证据不落账
    status           VARCHAR(20)  NOT NULL,                      -- PENDING/REMIND/RELEASED/VIOLATION/IGNORED
    open_flag        SMALLINT     NULL,                          -- PENDING=1，已处置=NULL（配合唯一索引）
    handler_id       BIGINT       NULL,
    handle_note      VARCHAR(200) NULL,
    photo_url        VARCHAR(200) NULL,
    create_time      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    handle_time      TIMESTAMP    NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_patrol_open
    ON t_patrol_task (seat_id, open_flag);
CREATE INDEX IF NOT EXISTS idx_patrol_status
    ON t_patrol_task (status, level, create_time);
CREATE INDEX IF NOT EXISTS idx_patrol_floor
    ON t_patrol_task (floor_id, open_flag, level);

