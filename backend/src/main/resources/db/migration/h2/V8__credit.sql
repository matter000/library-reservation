--
-- ★ 历史 no_show_count 的折算口径：只折算「起始信用分 + 一条 INIT 流水」，
--   **不伪造 t_violation 行**。理由：PRD §12-22「无证据不得裁定」，而 V1 时代的爽约
--   根本没有证据 JSON（无触发时刻快照、无操作人），补一条假证据等于自己破自己的规则。
--   折算后低于阈值的用户也不会立刻生成 t_penalty —— 阶梯由 CreditService 在
--   「下一次信用分变动」时评估，那一次是有完整证据的。
--
-- ★ 处罚阶梯（§6.2）与扣分幅度是产品口径，但阈值与开关走规则中心（CREDIT 组），
--   演示环境可把 credit.enforce_enabled 关掉 → 只记录不限制（DESIGN §17-6 逃生阀）。
--   新增规则键只能走迁移脚本，不做代码兜底写库。
