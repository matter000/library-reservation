-- =====================================================================
-- V5：桌位建模 + 座位坐标唯一约束（S1 / T-V2-06）
--
--   · t_table 是组队预约的最小单位；seat_count 由服务层与实际座位数校验保持一致。
--   · t_seat.table_id 允许为空：非组队区域（电子阅览、休闲阅览）不建模桌位。
--   · uk_seat_pos 修掉 V1 遗留缺陷：批量生成只校验 seat_no 唯一，不校验 (floor,row,col)
--     占位，导致同格叠出多个座位（实测 A01 / Z01 / Z488 同在 1 行 1 列）。
--
-- ★ 约束不降级：若遗留库确实存在重叠，本迁移会以唯一索引冲突**显式失败**，
--   而不是悄悄跳过建索引。运维处置办法见 docs/sql/fix-duplicate-seat-positions.sql
--   （把重叠座位顺延到该楼层底部的空行，保留数据、不删行）。
-- =====================================================================

CREATE TABLE IF NOT EXISTS t_table (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    zone_id     BIGINT       NOT NULL,
    floor_id    BIGINT       NOT NULL,                     -- 冗余，便于按楼层统计
    table_no    VARCHAR(20)  NOT NULL,                     -- 分区内唯一，如 T05
    seat_count  INT          NOT NULL DEFAULT 4,           -- 4~6
    status      VARCHAR(20)  NOT NULL DEFAULT 'AVAILABLE', -- AVAILABLE / MAINTENANCE / DISABLED
    remark      VARCHAR(200) NULL,
    create_time TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_table_zone_no ON t_table (zone_id, table_no);
CREATE INDEX IF NOT EXISTS idx_table_zone ON t_table (zone_id);
CREATE INDEX IF NOT EXISTS idx_table_floor ON t_table (floor_id);

ALTER TABLE t_seat ADD COLUMN IF NOT EXISTS table_id BIGINT NULL;
CREATE INDEX IF NOT EXISTS idx_seat_table ON t_seat (table_id);

-- ★ 本行是本次缺陷修复的落点：遗留数据若重叠会在此失败（故意的，见文件头说明）
CREATE UNIQUE INDEX IF NOT EXISTS uk_seat_pos ON t_seat (floor_id, row_no, col_no);
