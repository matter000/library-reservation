-- =====================================================================
-- V6：30 分钟时段 + 开放档案 / 开放日历 / 高峰窗口（S1 / T-V2-07）
--
-- ★ 时段格长由 1 小时改为 30 分钟：slot = (hour*60 + minute) / 30，end_slot 开区间。
--   现有数据必须整体 ×2，否则「V1 的第 14 格」会被读成 V2 的 07:00。
--   两张表在同一条脚本里改，保证预约与其 slot 明细不会错位。
--   乘二是单射（x*2 = y*2 ⟹ x = y），不会撞 uk_slot_seat_date_idx。
--
-- ★ duration 语义不变（仍是小时），换算由 BizConstants.slotsOf() 负责。
--
-- 开放档案按日型给出开闭馆边界（时段序号）：
--   WORKDAY 08:00-22:00 → 16..44，与 V1 完全一致，不因本次改造偷偷改产品口径；
--   需要 07:30-22:30 之类的窗口由管理面新增档案或日历覆盖，验收用例即按此断言 30 格。
-- =====================================================================

-- ---------- 1. 数据格长迁移（必须先于建档案，便于回滚时对照）----------
UPDATE t_reservation SET start_slot = start_slot * 2, end_slot = end_slot * 2;
UPDATE t_reservation_slot SET slot_index = slot_index * 2;

-- ---------- 2. 开放档案（按日型）----------
CREATE TABLE IF NOT EXISTS t_open_profile (
    id           BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    day_type     VARCHAR(20)  NOT NULL,                 -- WORKDAY / WEEKEND / HOLIDAY
    name         VARCHAR(50)  NOT NULL,
    open_start   INT          NOT NULL,                 -- 起始时段序号（含）
    open_end     INT          NOT NULL,                 -- 结束时段的开区间边界
    closed       BOOLEAN      NOT NULL DEFAULT FALSE,   -- 该日型整体闭馆
    enabled      BOOLEAN      NOT NULL DEFAULT TRUE,
    remark       VARCHAR(200) NULL,
    create_time  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_profile_day_type ON t_open_profile (day_type);

-- ---------- 3. 开放日历（具体日期覆盖档案）----------
CREATE TABLE IF NOT EXISTS t_open_calendar (
    id           BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    open_date    DATE         NOT NULL,
    day_type     VARCHAR(20)  NULL,                     -- 覆盖日型，可空表示沿用
    open_start   INT          NULL,                     -- 覆盖起始时段，可空表示沿用
    open_end     INT          NULL,
    closed       BOOLEAN      NOT NULL DEFAULT FALSE,   -- 临时闭馆：当日不可预约且平面图全灰
    remark       VARCHAR(200) NULL,
    create_time  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_calendar_date ON t_open_calendar (open_date);

-- ---------- 4. 高峰窗口（分区级或全馆级）----------
CREATE TABLE IF NOT EXISTS t_peak_window (
    id                BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scope             VARCHAR(20) NOT NULL DEFAULT 'GLOBAL', -- GLOBAL / FLOOR / ZONE
    floor_id          BIGINT      NULL,
    zone_id           BIGINT      NULL,
    name              VARCHAR(50) NOT NULL,
    day_types         VARCHAR(60) NOT NULL DEFAULT 'WORKDAY',  -- CSV 日型
    start_slot        INT         NOT NULL,
    end_slot          INT         NOT NULL,
    max_duration_min  INT         NULL,                       -- 高峰期间时长压缩上限
    advance_open_slot INT         NULL,                       -- 高峰时段提前开放的时段格（可空）
    enabled           BOOLEAN     NOT NULL DEFAULT TRUE,
    remark            VARCHAR(200) NULL,
    create_time       TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time       TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_peak_scope ON t_peak_window (scope, enabled);

