-- ★ 本系统没有任何第三方推送通道（无 MQ、无 WebSocket、无短信），
--   所谓「推送」= 写这张表 + 前端轮询（DESIGN §8.4）。验收要求把这句话写进文档，
--   是因为「收不到通知」在缺少推送通道时是设计后果而不是故障：候补 offer 只有 10 分钟窗口，
--   用户不开着页面就会错过 —— UI 必须把这点讲出来，而不是假装消息能送到手机上。
--
-- ★ uk_notice_ref 是幂等的唯一真相：提醒任务每分钟跑一次，「先查再插」只是省一次写入的
--   友好路径，并发或补跑时真正拦住重复消息的是这个唯一索引。
--   去重键取（谁 + 哪类 + 指向哪条业务记录）：一条暂离记录、一次候补 offer、一笔违规，
--   都只该打扰用户一次。ref_id 为 NULL 的行不参与去重（H2/MySQL 都不把多行 NULL 视为冲突），
--   目前所有生产者都带 ref，所以这条只是留给未来「无对象广播」的出口。
--
-- ★ 不做 PEAK_TIP 生产者：高峰对用户唯一可操作的时刻是「还没下单之前」，
--   而那一份已经由平面图 / 余量卡片上的 peakFlag 交付（T-V2-18）。
--   下单之后再发一条「你预约的时段现在是高峰」，用户什么也做不了，只是噪音。
-- =====================================================================

CREATE TABLE IF NOT EXISTS t_notice (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL,
    type        VARCHAR(30)  NOT NULL,                      -- 见 NoticeType：CHECK_IN_REMIND/LEAVE_OPEN/LEAVE_EXPIRE/VIOLATION/APPEAL_RESULT/WAITLIST_OFFER/GROUP_LEADER_ABSENT
    title       VARCHAR(50)  NOT NULL,
    content     VARCHAR(300) NOT NULL,
    ref_type    VARCHAR(20)  NULL,                          -- RESERVATION/LEAVE/WAITLIST/VIOLATION/APPEAL/GROUP
    ref_id      BIGINT       NULL,
    read_flag   BOOLEAN      NOT NULL DEFAULT FALSE,        -- 已读只是阅读状态，不是唯一性，所以不用 active_flag 那套 NULL 技巧
    expire_time TIMESTAMP    NULL,                          -- 有行动窗口的通知（候补 offer）带截止时刻，UI 才能显示「已过期」
    create_time TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_notice_ref
    ON t_notice (user_id, type, ref_type, ref_id);
CREATE INDEX IF NOT EXISTS idx_notice_user
    ON t_notice (user_id, read_flag, create_time);

