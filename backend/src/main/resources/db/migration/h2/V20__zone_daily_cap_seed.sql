-- V20：把 1F-SILENT 的分区级单日累计追平到种子口径，让「已迁移老库」与「新建库」取值一致（B9）
--
-- ★ 这条迁移的方向和 V17 相反，必须说清楚，否则会被读成"又拿迁移去改种子"：
--   t_zone 的 8 个演示分区是 DataInitializer（Java）写的，而 Flyway 永远跑在 Java 种子**之前** ——
--   所以 V17 那句 `UPDATE t_zone SET daily_cap_min = NULL` 在空库上命中 0 行，
--   新建库随后又被种子写成 480（那半边已改种子修正，见 DESIGN §14.3）。
--   1F-SILENT 是反过来的情形：360 是**现在**的种子值（B3 那轮加的），
--   而演示库里的分区行加值之前就种下了，于是停在 NULL。
--   本条只把老库追平到种子，不动种子；新建库执行到这里也是 0 行变更（它本来就已经是 360），
--   于是两种建库路径收敛到同一份规则值。
--
-- ★ 为什么 360 值得留在分区上而不是撤掉：
--   `CreditPenaltyApiTest.dailyCapEnforced` 需要一个"配了单日上限的分区"来证明分区那道闸门
--   独立生效（它断言 cap > 0，并验证报错给出已用/上限）。哪天要撤这个种子值，
--   必须同时让用例自己配值，否则那条闸门就没了覆盖。
--
-- WHERE 里带 `IS NULL`：馆员如果显式改过本区上限，就不要被一次升级盖掉。
-- =====================================================================

UPDATE t_zone SET daily_cap_min = 360
WHERE code = '1F-SILENT' AND daily_cap_min IS NULL;
