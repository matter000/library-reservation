-- V7：暂离（S2 / T-V2-09）
--
-- ★ 与 TASKS-V2 的编号说明：任务表写的是 V6__leave.sql，但 V6 已被
--   「30 分钟时段 + 开放日历」占用（S1 先行落地），故本片顺延为 V7。
--
-- ★ uk_leave_open (reservation_id, open_flag) 用「open_flag 仅 OPEN 时 =1，
--   结束后置 NULL」实现「一条预约同时至多一条 OPEN 暂离」。
--   NULL 在唯一索引里互不相等（H2 2.x 与 MySQL 都遵守 SQL 标准这一条），
--   所以历史记录可以有多条，活跃记录只能有一条 —— 不靠「先查后插」，
--   并发下由索引兜住（这是 V1 抢座 uk_slot_seat_date_idx 的同一套打法）。
--
-- ★ 原因的 need_note：DESIGN §5.1 注释是「上课/会议需填事由」，而原因码里
--   没有「会议」，语义上「其他(OTHER)」同样必须写明事由，故 CLASS 与 OTHER
--   置 TRUE。管理面后续可改此列，不需要迁移脚本。
--
-- ★ 每日次数是「双重上限」：min(t_zone.leave_daily_limit, t_leave_reason.daily_limit)，
--   本表只存原因侧上限，分区侧上限沿用 V4 已建的列。
-- =====================================================================

CREATE TABLE IF NOT EXISTS t_leave_reason (
    code         VARCHAR(30)  NOT NULL PRIMARY KEY,     -- MEAL/CLASS/PHONE/REST/PICKUP/OTHER
    name         VARCHAR(50)  NOT NULL,
    max_min      INT          NOT NULL,                 -- 单次最长暂离分钟
    daily_limit  INT          NOT NULL DEFAULT 3,       -- 该原因每日次数上限
    need_note    BOOLEAN      NOT NULL DEFAULT FALSE,   -- 必须填事由
    enabled      BOOLEAN      NOT NULL DEFAULT TRUE,
    sort_order   INT          NOT NULL DEFAULT 0,
    create_time  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS t_leave_record (
    id                 BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id     BIGINT       NOT NULL,
    user_id            BIGINT       NOT NULL,
    seat_id            BIGINT       NOT NULL,
    reason_code        VARCHAR(30)  NOT NULL,
    note               VARCHAR(100) NULL,
    start_time         TIMESTAMP    NOT NULL,
    planned_end_time   TIMESTAMP    NOT NULL,           -- 已按分区上限与预约结束时间双重截断
    actual_return_time TIMESTAMP    NULL,
    status             VARCHAR(20)  NOT NULL,           -- OPEN / RETURNED / TIMEOUT
    open_flag          SMALLINT     NULL,               -- ★ OPEN 时 =1，结束置 NULL
    create_time        TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time        TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_leave_open    ON t_leave_record (reservation_id, open_flag);
CREATE INDEX        IF NOT EXISTS idx_leave_user_date ON t_leave_record (user_id, start_time);
CREATE INDEX        IF NOT EXISTS idx_leave_status    ON t_leave_record (status, planned_end_time);

