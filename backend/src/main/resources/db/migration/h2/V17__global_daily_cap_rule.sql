-- =====================================================================
-- V17：把「单日累计上限」补成全馆口径（T-V2-24 / B3，PRD §12-3）
--
-- ★ 为什么要有这一版：
--   PRD §12-3 写的是「单日累计上限 6 小时」——这条规则挂在**人**身上。
--   V2 落地时只有 t_zone.daily_cap_min 一个分区级字段，闸门也只读它，于是
--   "今天一共坐了多久"从来没有被算过：一个学生换五个区各约 4 小时，
--   没有一道闸门会响，而规则中心里连一个能表达这条规则的键都不存在。
--   本轮逐条对账 PRD §12 时这是第三处"配置写进了库、却没有任何消费路径"。
--
-- ★ 同时把考研专座的 daily_cap_min 置 NULL：
--   它原来写着 480 分钟（8 小时），比新的全馆 360 更宽。分区级上限的语义是
--   "本区累计不超过多少"，比全馆更宽并不矛盾，但会让人误以为"在考研专座可以坐 8 小时/天"——
--   实际全馆 360 先拦。既然 PRD 从没给任何分区放过单日额度，就把这个误导性的值撤掉，
--   让它跟随全馆规则（需要放宽时改 book.daily-cap-min 即可，不发版）。
--
-- ★ 两道检查是独立的，不是取小：分区口径管"本区"，全馆口径管"这个人今天"。
-- =====================================================================

INSERT INTO t_rule_config (scope, scope_id, rkey, rvalue, value_type, rgroup, editable, description) VALUES
    ('GLOBAL', '', 'book.daily-cap-min', '360', 'INT', 'BOOK', TRUE,
     '单日累计预约上限（分钟，全馆口径，换分区也一样计入；PRD §12-3 的 6 小时）');

UPDATE t_zone SET daily_cap_min = NULL WHERE code = '3F-EXAM';
