-- =====================================================================
-- V18：教师单次时长上限改回 6 小时（T-V2-24 / B2，PRD §12-2）
--
-- ★ 为什么是数据修复而不是代码修复：
--   PRD §12-2 写「单次上限 4 小时（教师 6 小时）」，但 V11 播种时把
--   book.max-duration-teacher-min 写成了 240 —— 与学生的 4 小时一模一样，
--   于是这条规则从落库那天起就是空转：教师挑不到 5/6 小时那一档，
--   硬调接口也被"时长只能选择 1/2/3/4 小时"拦下。
--   本轮把它接进 allowedDurations(role) 之后，这个 240 才第一次真正暴露出来。
--
-- ★ 顺带把说明写准：原描述"用于覆盖分区上限"只对高峰那条分支成立，
--   非高峰时分区自己的单次上限仍然优先（§14.1：分区是本区口径）。
--   教师在静音自习区（240）不能约 6 小时，在教师专区（360）可以。
-- =====================================================================

UPDATE t_rule_config
   SET rvalue = '360',
       description = '教师单次时长上限（分钟，PRD §12-2 的 6 小时）；非高峰时仍受分区单次上限约束'
 WHERE rkey = 'book.max-duration-teacher-min';
