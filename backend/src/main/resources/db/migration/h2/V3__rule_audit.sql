-- =====================================================================
-- V3：规则配置中心 + 审计日志（S0）
--   · t_rule_config 让业务阈值「后台可配、不发版」；
--   · scope_id 用空串而非 NULL —— NULL 在唯一索引中互不相等，
--     GLOBAL 作用域若用 NULL 会让「同 key 重复插入」逃过约束。
--   · 只种已接线消费的键（未接线的配置等于死配置，随各片逐个加入）。
-- =====================================================================

CREATE TABLE IF NOT EXISTS t_rule_config (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scope       VARCHAR(20)  NOT NULL,                 -- GLOBAL / ZONE / DAY_TYPE
    scope_id    VARCHAR(30)  NOT NULL DEFAULT '',      -- 作用域对象 ID；GLOBAL 为空串
    rkey        VARCHAR(50)  NOT NULL,
    rvalue      VARCHAR(200) NOT NULL,
    value_type  VARCHAR(10)  NOT NULL DEFAULT 'STRING',-- INT / BOOL / TIME / STRING / INT_LIST
    rgroup      VARCHAR(30)  NOT NULL DEFAULT 'BOOK',  -- OPEN/BOOK/LEAVE/CREDIT/PEAK/PATROL
    editable    BOOLEAN      NOT NULL DEFAULT TRUE,
    description VARCHAR(200) NULL,
    updated_by  BIGINT       NULL,
    create_time TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_rule ON t_rule_config (scope, scope_id, rkey);
CREATE INDEX IF NOT EXISTS idx_rule_group ON t_rule_config (rgroup);

CREATE TABLE IF NOT EXISTS t_audit_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id    BIGINT       NULL,
    actor_role  VARCHAR(20)  NULL,
    action      VARCHAR(50)  NOT NULL,
    target_type VARCHAR(30)  NOT NULL,
    target_id   VARCHAR(30)  NULL,
    detail      CLOB         NULL,
    create_time TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_audit_time ON t_audit_log (create_time);
CREATE INDEX IF NOT EXISTS idx_audit_actor ON t_audit_log (actor_id, create_time);

