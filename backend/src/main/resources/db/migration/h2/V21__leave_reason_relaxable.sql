ALTER TABLE t_leave_reason ADD COLUMN relaxable BOOLEAN NOT NULL DEFAULT FALSE;

-- 标准上限级：这两条本来就是"离开较久"的原因，允许由分区按本区口径放宽
UPDATE t_leave_reason SET relaxable = TRUE WHERE code IN ('MEAL', 'CLASS');
