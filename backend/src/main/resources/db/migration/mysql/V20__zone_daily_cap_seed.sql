-- =====================================================================
-- V20：把 1F-SILENT 的分区级单日累计追平到种子口径（与 h2/V20 同义，B9）
--
-- 分区行由 DataInitializer（Java）写，而迁移跑在它之前：V17 撤 480 那步对新建库是空操作，
-- 1F-SILENT 则是老库落后于当前种子值（360 是 B3 那轮才加进种子的）。
-- 本条只追平老库，不动种子；新建库执行时命中 0 行，两种建库路径因此取值一致。
-- 详见 DESIGN §14.3。
--
-- WHERE 带 `IS NULL`：馆员显式改过本区上限时不被升级盖掉。
-- =====================================================================

UPDATE t_zone SET daily_cap_min = 360
WHERE code = '1F-SILENT' AND daily_cap_min IS NULL;
